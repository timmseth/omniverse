#!/usr/bin/env python3
"""Regenerate app/src/main/assets/dungeons.js from the Omniverse dungeon index.

Usage:  python3 tools/sync_data.py [path/to/dungeons.json]

By default it reads <repo root>/_generated/dungeons.json (this app lives in
<repo root>/Apps/dmScreen). Run `python3 _rules/tools/build_dungeons.py .`
first if the index is out of date.
"""
import json
import sys
from pathlib import Path

here = Path(__file__).resolve().parent
app = here.parent
src = Path(sys.argv[1]) if len(sys.argv) > 1 else app.parent.parent / "_generated" / "dungeons.json"
out = app / "app" / "src" / "main" / "assets" / "dungeons.js"

data = json.loads(src.read_text(encoding="utf-8"))
if data.get("schema") != 1 or not isinstance(data.get("dungeons"), list):
    sys.exit("error: %s is not a schema-1 dungeon index" % src)
codes = [d.get("code") for d in data["dungeons"]]
if len(set(codes)) != len(codes):
    sys.exit("error: dungeon codes are not unique: %s" % codes)

text = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
out.write_text("/* generated by tools/sync_data.py from _generated/dungeons.json - do not edit */\n"
               "window.BUNDLED_DUNGEONS=" + text + ";\n", encoding="utf-8")
print("wrote %s: %d dungeons, %d rooms, %d KB" % (
    out.relative_to(app), len(data["dungeons"]),
    sum(len(d["rooms"]) for d in data["dungeons"]), out.stat().st_size // 1024))
