#!/usr/bin/env python3
"""Build the world index: _generated/world.json, _generated/World Index.md and
_generated/Backlinks.md from every note in the repository.

Usage:  python3 _rules/tools/build_world.py <repo root> [--check]

world.json (schema 1) is the "world API": one entry per note with its frontmatter,
body, outgoing references and incoming references, so apps and skills can read the
whole Omniverse without parsing Markdown. Rooms are summarised here and given in
full by build_dungeons.py (_generated/dungeons.json).
"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import validate as V

SCHEMA_VERSION = 1
SOURCE = "https://github.com/timmseth/omniverse"
LINK = re.compile(r"\[\[([^\]|#]+)(?:#[^\]|]*)?(?:\|[^\]]*)?\]\]")
BODY_KINDS_SKIP = {"room", "generated", "template"}


def body_of(path):
    src = open(path, encoding="utf-8").read()
    m = re.match(r"^---\r?\n(.*?)\r?\n---\r?\n", src, re.S)
    return src[m.end():].strip() if m else src.strip()


def main(argv):
    if len(argv) < 2:
        print(__doc__); return 2
    root, check = argv[1], "--check" in argv
    notes, names, _ = V.load_notes(root)
    byname = {}
    for i, (rel, meta) in notes.items():
        byname[os.path.basename(rel)[:-3]] = i
    entries, children, refby = {}, {}, {}
    for i, (rel, meta) in notes.items():
        kind = meta.get("kind")
        refs = sorted({r for r in V_walk(meta) if r in notes and r != i})
        body = "" if kind in BODY_KINDS_SKIP else body_of(os.path.join(root, rel))
        links = sorted({byname[t.strip().replace("\\", "")] for t in LINK.findall(body) if t.strip().replace("\\", "") in byname} - {i})
        data = {k: v for k, v in meta.items() if k not in ("id", "kind", "name", "parent", "universe")}
        if kind == "room":
            data = {k: data.get(k) for k in ("number", "code", "dungeon") if k in data}
        entries[i] = {
            "id": i, "kind": kind, "name": meta.get("name"), "universe": meta.get("universe"),
            "parent": meta.get("parent"), "path": rel, "summary": meta.get("summary") or "",
            "tags": meta.get("tags") or [], "status": meta.get("status"),
            "refs": refs, "links": links, "referencedBy": [], "children": [], "data": data,
            "body": body if kind not in BODY_KINDS_SKIP else "",
        }
        p = meta.get("parent")
        if p in notes:
            children.setdefault(p, []).append(i)
        for r in set(refs) | set(links):
            refby.setdefault(r, set()).add(i)
    for i, e in entries.items():
        e["children"] = sorted(children.get(i, []))
        e["referencedBy"] = sorted(refby.get(i, []))
    counts = {}
    for e in entries.values():
        counts[e["kind"]] = counts.get(e["kind"], 0) + 1
    universes = [{"id": i, "name": e["name"], "tone": e["data"].get("tone"), "ruleset": e["data"].get("ruleset"),
                  "status": e["data"].get("status"), "maintainers": e["data"].get("maintainers")}
                 for i, e in entries.items() if e["kind"] == "universe"]
    out = {"schema": SCHEMA_VERSION, "source": SOURCE, "counts": counts, "universes": universes,
           "notes": [entries[k] for k in sorted(entries)]}
    gen = os.path.join(root, "_generated")
    os.makedirs(gen, exist_ok=True)
    if not check:
        with open(os.path.join(gen, "world.json"), "w", encoding="utf-8", newline="\n") as f:
            json.dump(out, f, ensure_ascii=False, indent=1, default=str)
            f.write("\n")
        write_index(gen, entries, counts)
        write_backlinks(gen, entries)
    print("world: %d notes, %d kinds%s" % (len(entries), len(counts), "" if not check else " (check only)"))
    return 0


def V_walk(meta):
    for k, v in meta.items():
        if k == "id": continue
        yield from walk(v)


def walk(v):
    if isinstance(v, str):
        if re.match(r"^[a-z0-9-]+(\.[a-z0-9_-]+)+$", v): yield v
    elif isinstance(v, list):
        for x in v: yield from walk(x)
    elif isinstance(v, dict):
        for x in v.values(): yield from walk(x)


def link(e):
    return "[[%s]]" % os.path.basename(e["path"])[:-3].replace("|", "\\|")


def write_index(gen, entries, counts):
    order = ["universe", "plane", "galaxy", "star_system", "planet", "continent", "region", "country", "province", "settlement", "district", "venue",
             "household", "person", "faction", "deity", "culture", "language", "calendar", "holiday", "era", "event", "trope", "trope_instance",
             "quest", "lore", "table", "dungeon", "monster", "item", "instance", "campaign", "session", "ruleset", "module", "index", "guide"]
    lines = ["---", "kind: generated", "generated: build_world.py", "---", "# World Index", "",
             "*(Do not edit. Regenerated by `_rules/tools/build_world.py`.)*", "",
             "| Kind | Count |", "|---|---|"] + ["| %s | %d |" % (k, counts[k]) for k in order + sorted(set(counts) - set(order)) if k in counts]
    for k in order + sorted(set(counts) - set(order)):
        es = sorted((e for e in entries.values() if e["kind"] == k), key=lambda e: (e["universe"] or "", e["name"] or ""))
        if not es or k == "room": continue
        lines += ["", "## %s (%d)" % (k, len(es)), "", "| Note | Universe | Id | Refs in |", "|---|---|---|---|"]
        for e in es:
            lines.append("| %s | %s | `%s` | %d |" % (link(e), e["universe"] or "", e["id"], len(e["referencedBy"])))
    open(os.path.join(gen, "World Index.md"), "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")


def write_backlinks(gen, entries):
    lines = ["---", "kind: generated", "generated: build_world.py", "---", "# Backlinks", "",
             "*(Do not edit. Regenerated by `_rules/tools/build_world.py`. What references what, by id and by wikilink.)*", ""]
    for i in sorted(entries):
        e = entries[i]
        if e["kind"] == "room" or not e["referencedBy"]: continue
        lines.append("## %s `%s`" % (link(e), i))
        for r in e["referencedBy"]:
            if entries[r]["kind"] == "room": continue
            lines.append("- %s (%s)" % (link(entries[r]), entries[r]["kind"]))
        rooms = [r for r in e["referencedBy"] if entries[r]["kind"] == "room"]
        if rooms: lines.append("- %d room%s" % (len(rooms), "" if len(rooms) == 1 else "s"))
        lines.append("")
    open(os.path.join(gen, "Backlinks.md"), "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    sys.exit(main(sys.argv))
