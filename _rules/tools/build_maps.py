#!/usr/bin/env python3
"""Draw a schematic map of each universe's place tree as SVG: planet, continents, regions,
settlements, with dungeons marked. Writes _generated/Maps/<Universe>.svg and _generated/Maps.md.
Usage: python3 _rules/tools/build_maps.py <repo root>
"""
import os, sys, html
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import validate as V

LEVELS = ["planet", "continent", "region", "country", "province", "settlement"]
COL = {"planet": "#e3a72f", "continent": "#c08a2a", "region": "#6b8f5e", "country": "#5b7fb5", "province": "#7a6fb0", "settlement": "#d9d2e0"}


def main(root):
    notes, names, _ = V.load_notes(root)
    out_dir = os.path.join(root, "_generated", "Maps")
    os.makedirs(out_dir, exist_ok=True)
    md = ["---", "kind: generated", "generated: build_maps.py", "---", "# Maps", "", "*(Do not edit. Regenerated by `_rules/tools/build_maps.py` from the place tree.)*", ""]
    for uid, (urel, um) in sorted(notes.items()):
        if um.get("kind") != "universe": continue
        places = {i: m for i, (r, m) in notes.items() if m.get("universe") == uid and m.get("kind") in LEVELS}
        dungeons = {}
        for i, (r, m) in notes.items():
            if m.get("universe") == uid and m.get("kind") == "dungeon":
                dungeons.setdefault(m.get("parent"), []).append(m)
        kids = {}
        for i, m in places.items():
            kids.setdefault(m.get("parent"), []).append(i)
        roots = [i for i, m in places.items() if m.get("kind") == "planet"]
        # layout: depth-first, leaves get a row each
        pos, rows = {}, [0]
        def place(i, depth):
            ch = sorted(kids.get(i, []), key=lambda k: places[k].get("name", ""))
            if not ch:
                pos[i] = (depth, rows[0]); rows[0] += 1; return rows[0] - 1
            first = last = None
            for c in ch:
                r = place(c, depth + 1)
                first = r if first is None else first; last = r
            pos[i] = (depth, (first + last) / 2.0)
            return (first + last) / 2.0
        for r in sorted(roots, key=lambda k: places[k].get("name", "")):
            place(r, 0)
            rows[0] += 1
        if not pos: continue
        CW, RH, W0, H0 = 200, 40, 30, 30
        maxd = max(d for d, _ in pos.values())
        width = W0 * 2 + (maxd + 1) * CW + 120
        height = H0 * 2 + max(rows[0], 1) * RH
        svg = ['<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d" font-family="Georgia, serif" font-size="13">' % (width, height, width, height),
               '<rect width="100%%" height="100%%" fill="#15131a"/>',
               '<text x="%d" y="20" fill="#e3a72f" font-size="16">%s: places and dungeons</text>' % (W0, html.escape(um.get("name", uid)))]
        def xy(i):
            d, r = pos[i]; return W0 + d * CW, H0 + 10 + r * RH + RH / 2
        for i, m in places.items():
            p = m.get("parent")
            if p in pos:
                x1, y1 = xy(p); x2, y2 = xy(i)
                svg.append('<path d="M%d,%d C%d,%d %d,%d %d,%d" stroke="#4a4458" fill="none"/>' % (x1 + 150, y1, x1 + 180, y1, x2 - 30, y2, x2, y2))
        for i, m in places.items():
            x, y = xy(i); k = m.get("kind")
            svg.append('<rect x="%d" y="%d" width="150" height="32" rx="6" fill="#221e2b" stroke="%s"/>' % (x, y - 16, COL.get(k, "#888")))
            svg.append('<text x="%d" y="%d" fill="#eee">%s</text>' % (x + 8, y - 2, html.escape(m.get("name", "")[:21])))
            svg.append('<text x="%d" y="%d" fill="#8a8396" font-size="9">%s</text>' % (x + 8, y + 11, k))
            ds = dungeons.get(i, [])
            if ds:
                svg.append('<text x="%d" y="%d" fill="#e3a72f" font-size="10" text-anchor="end">%s</text>' % (x + 144, y + 11, html.escape(" ".join(d.get("code", "?") for d in ds))))
        svg.append("</svg>")
        fn = "%s.svg" % um.get("name", uid)
        open(os.path.join(out_dir, fn), "w", encoding="utf-8", newline="\n").write("\n".join(svg) + "\n")
        md += ["## %s" % um.get("name"), "", "![[Maps/%s]]" % fn, "", "%d places, %d dungeons." % (len(places), sum(len(v) for v in dungeons.values())), ""]
        print("map: %s, %d places" % (um.get("name"), len(places)))
    open(os.path.join(root, "_generated", "Maps.md"), "w", encoding="utf-8", newline="\n").write("\n".join(md))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
