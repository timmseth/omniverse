#!/usr/bin/env python3
"""Generate <universe>/_timeline.md for every universe: eras, canon events in order,
and the instances forked from canon.  Usage: python3 _rules/tools/build_timeline.py <repo root>
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import validate as V


def wl(rel):
    return "[[%s]]" % os.path.basename(rel)[:-3]


def main(root):
    notes, names, _ = V.load_notes(root)
    unis = [(i, rel, m) for i, (rel, m) in notes.items() if m.get("kind") == "universe"]
    for uid, urel, um in unis:
        eras = sorted(((rel, m) for rel, m in notes.values() if m.get("kind") == "era" and m.get("universe") == uid), key=lambda x: (x[1].get("from") or {}).get("year", -10**9) if isinstance(x[1].get("from"), dict) else -10**9)
        events = sorted(((rel, m) for rel, m in notes.values() if m.get("kind") == "event" and m.get("universe") == uid), key=lambda x: (x[1]["when"].get("year", 0), x[1]["when"].get("day", 0), x[1].get("id", "")))
        insts = sorted((i, rel, m) for i, (rel, m) in notes.items() if m.get("kind") == "instance" and m.get("universe") == uid)
        latest = events[-1][1]["when"] if events else {"year": 0, "day": 0}
        out = ["---", "kind: generated", "generated: build_timeline.py", "about: %s" % uid, "as_of: { year: %s, day: %s }" % (latest.get("year"), latest.get("day", 0)), "---",
               "# %s timeline" % um.get("name"), "", "*(Do not edit. Regenerated by `_rules/tools/build_timeline.py` from the canon events and the instances.)*", "",
               "## Eras", "", "| Era | From | To | Character |", "|---|---|---|---|"]
        for rel, m in eras:
            f = m.get("from"); t = m.get("to")
            fs = "primordial" if f == "primordial" else ("year %s" % f.get("year") if isinstance(f, dict) else "")
            ts = "now" if t is None else ("year %s" % t.get("year") if isinstance(t, dict) else str(t))
            out.append("| %s | %s | %s | %s |" % (wl(rel), fs, ts, m.get("character") or ""))
        out += ["", "## Canon events (%d)" % len(events), "", "| Year | Day | Event | Where | Type | Severity | Visibility |", "|---|---|---|---|---|---|---|"]
        for rel, m in events:
            w = m.get("where"); wn = notes[w][1].get("name") if w in notes else (w or "")
            out.append("| %s | %s | %s | %s | %s | %s | %s |" % (m["when"].get("year"), m["when"].get("day", ""), wl(rel), wn, m.get("type"), m.get("severity"), m.get("visibility")))
        out += ["", "## Instances (%d)" % len(insts), "", "| Instance | Status | Visibility | Fork point | Sessions | Events logged |", "|---|---|---|---|---|---|"]
        for iid, rel, m in insts:
            sess = [sm for sr, sm in notes.values() if sm.get("kind") == "session" and sm.get("campaign") == iid]
            nev = sum(len(sm.get("events") or []) for sm in sess)
            fp = m.get("fork_point") or {}
            out.append("| [[%s\\|%s]] | %s | %s | %s day %s | %d | %d |" % (rel[:-3], m.get("name"), m.get("status"), m.get("visibility"), fp.get("year"), fp.get("day"), len(sess), nev))
        p = os.path.join(root, os.path.dirname(urel), "_timeline.md")
        open(p, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
        print("timeline: %s, %d eras, %d events, %d instances" % (um.get("name"), len(eras), len(events), len(insts)))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
